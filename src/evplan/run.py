logger = get_logger(__name__)


def run_data_stage() -> dict:
    """Stage 1: Download, load, clean, and integrate all datasets."""
    from evplan.data.download import download_all
    from evplan.data.loaders import load_all
    from evplan.data.clean import clean_demand, clean_stations, clean_adoption

    logger.info("=" * 60)
    logger.info("STAGE 1: DATA — Download, Load, Clean")
    logger.info("=" * 60)

    # Download
    download_results = download_all()
    logger.info("Download results: %s", download_results)

    # Load
    raw = load_all()

    results = {}

    # Clean demand
    if raw["demand"] is not None:
        demand_clean, quality_report = clean_demand(raw["demand"])
        # Save
        proc_dir = get_path("data_processed")
        Path(proc_dir).mkdir(parents=True, exist_ok=True)
        demand_clean.to_parquet(str(Path(proc_dir) / "demand_clean.parquet"), index=False)
        Path(get_path("docs")).mkdir(parents=True, exist_ok=True)
        (Path(get_path("docs")) / "data_quality_demand.json").write_text(
            json.dumps(quality_report, indent=2, default=str)
        )
        results["demand"] = demand_clean
        logger.info("Demand dataset: %d rows after cleaning.", len(demand_clean))
    else:
        logger.warning("Demand dataset unavailable.")
        results["demand"] = None

    # Clean stations
    if raw["stations"] is not None:
        stations_clean = clean_stations(raw["stations"])
        stations_clean.to_parquet(str(Path(get_path("data_processed")) / "stations_clean.parquet"), index=False)
        results["stations"] = stations_clean
    else:
        results["stations"] = None

    # Clean adoption
    if raw["adoption"] is not None:
        adoption_clean = clean_adoption(raw["adoption"])
        adoption_clean.to_parquet(str(Path(get_path("data_processed")) / "adoption_clean.parquet"), index=False)
        results["adoption"] = adoption_clean
    else:
        results["adoption"] = None

    # Write data audit
    _write_data_audit(raw, results)

    return results


def _write_data_audit(raw: dict, clean: dict) -> None:
    """Write docs/data_audit.md based on actual dataset findings."""
    import pandas as pd

    docs_dir = get_path("docs")
    Path(docs_dir).mkdir(parents=True, exist_ok=True)

    lines = ["# Data Audit\n", f"Generated by EV XAI Planner pipeline.\n\n"]

    for name, df in raw.items():
        if df is None:
            lines.append(f"## {name.title()} Dataset\n**Status:** Not available / not downloaded yet.\n\n")
            lines.append(f"### Manual Download Instructions\nSee `docs/data_integration.md`.\n\n")
            continue

        lines.append(f"## {name.title()} Dataset\n")
        lines.append(f"- **Rows:** {len(df):,}\n")
        lines.append(f"- **Columns:** {len(df.columns)}\n")
        lines.append(f"- **Column names:** `{list(df.columns)}`\n")
        lines.append(f"- **dtypes:**\n```\n{df.dtypes.to_string()}\n```\n")

        null_pct = (df.isnull().mean() * 100).round(1)
        high_null = null_pct[null_pct > 10]
        if not high_null.empty:
            lines.append(f"- **Columns with >10% nulls:** `{high_null.to_dict()}`\n")
        else:
            lines.append(f"- **Nulls:** No columns with >10% missing values.\n")

        # Check for lat/lon
        has_coords = any(c in df.columns for c in ["latitude", "longitude", "lat", "lon"])
        lines.append(f"- **Has coordinates:** {'Yes' if has_coords else 'No'}\n")

        if clean.get(name) is not None:
            lines.append(f"- **Rows after cleaning:** {len(clean[name]):,}\n")
        lines.append("\n")

    audit_path = Path(docs_dir) / "data_audit.md"
    audit_path.write_text("".join(lines), encoding="utf-8")
    logger.info("Data audit written to %s", audit_path)


def run_features_stage(demand_df=None, stations_df=None, adoption_df=None) -> dict:
    """Stage 2: Feature engineering."""
    import pandas as pd
    from evplan.features.engineer import engineer_features, get_feature_columns
    from evplan.gis.zones import build_zone_table

    logger.info("=" * 60)
    logger.info("STAGE 2: FEATURE ENGINEERING")
    logger.info("=" * 60)

    # Load from disk if not provided
    proc_dir = get_path("data_processed")

    def _load(name):
        p = Path(proc_dir) / f"{name}_clean.parquet"
        return pd.read_parquet(p) if p.exists() else None

    demand_df = demand_df if demand_df is not None else _load("demand")
    stations_df = stations_df if stations_df is not None else _load("stations")
    adoption_df = adoption_df if adoption_df is not None else _load("adoption")

    # Build zone table
    zone_df = build_zone_table(demand_df, stations_df, adoption_df)
    zone_df.to_parquet(str(Path(proc_dir) / "zone_table.parquet"), index=False)

    if demand_df is not None:
        feat_df = engineer_features(demand_df, zone_stats=zone_df)
        feat_df.to_parquet(str(Path(proc_dir) / "features.parquet"), index=False)
        logger.info("Feature engineering complete: %d rows, %d features", len(feat_df), len(feat_df.columns))
        return {"features": feat_df, "zone_df": zone_df}
    else:
        logger.warning("No demand data — using zone table only for features.")
        return {"features": None, "zone_df": zone_df}


def run_train_stage(features_df=None) -> dict:
    """Stage 3: Model training with tuning."""
    import pandas as pd
    from evplan.models.train import train_pipeline

    logger.info("=" * 60)
    logger.info("STAGE 3: MODEL TRAINING")
    logger.info("=" * 60)

    if features_df is None:
        p = Path(get_path("data_processed")) / "features.parquet"
        if p.exists():
            features_df = pd.read_parquet(p)
        else:
            logger.error("No feature data found. Run data+features stages first.")
            return {}

    cfg = load_config()
    n_trials = cfg["optuna"]["n_trials"]
    result = train_pipeline(features_df, tune=True, n_trials=n_trials)
    return result


def run_explain_stage(train_results=None) -> dict:
    """Stage 4: SHAP explainability."""
    import pandas as pd
    from evplan.explain.shap_explain import (
        compute_shap_values, generate_global_plots,
        generate_dependence_plots, get_global_importance,
        consistency_check, narrative_explanation, local_explanation,
    )
    from evplan.models.train import load_model

    logger.info("=" * 60)
    logger.info("STAGE 4: SHAP EXPLAINABILITY")
    logger.info("=" * 60)

    results = {}
    cfg = load_config()
    max_samples = cfg["shap"]["max_samples"]

    model_names = []
    if cfg["models"]["rf"]["enabled"]:
        model_names.append(("random_forest", "rf"))
    if cfg["models"]["xgboost"]["enabled"]:
        model_names.append(("xgboost", "xgboost"))

    shap_store = {}
    for model_file, model_key in model_names:
        model = load_model(model_file) if train_results is None else train_results.get("results", {}).get(
            {"rf": "Random Forest", "xgboost": "XGBoost"}.get(model_key, model_key), {}).get("model")
        if model is None:
            model = load_model(model_file)
        if model is None:
            continue

        X_test = train_results.get("X_test") if train_results else None
        if X_test is None:
            p = Path(get_path("data_processed")) / "features.parquet"
            if p.exists():
                feat_df = pd.read_parquet(p)
                feat_cols = [c for c in feat_df.columns if c != cfg["data"]["target_column"]]
                feat_cols = [c for c in feat_cols if pd.api.types.is_numeric_dtype(feat_df[c])]
                X_test = feat_df[feat_cols]

        if X_test is None:
            continue

        shap_vals, explainer = compute_shap_values(model, X_test, model_name=model_key, max_samples=max_samples)
        generate_global_plots(shap_vals, X_test, model_name=model_key)
        generate_dependence_plots(shap_vals, X_test, model_name=model_key)

        importance = get_global_importance(shap_vals)
        importance.to_csv(get_path("tables") / f"shap_importance_{model_key}.csv", index=False)

        # Local explanations for extreme cases within the computed SHAP sample
        n_shap = len(shap_vals.values) if hasattr(shap_vals, "values") else len(shap_vals)
        if hasattr(shap_vals, "data") and shap_vals.data is not None:
            sample_data = pd.DataFrame(shap_vals.data, columns=X_test.columns)
            y_pred_sample = model.predict(sample_data)
        else:
            y_pred_sample = model.predict(X_test.iloc[:n_shap])

        for idx_name, idx in [("highest", int(y_pred_sample.argmax())), ("lowest", int(y_pred_sample.argmin()))]:
            local_explanation(shap_vals, idx, model_name=f"{model_key}_{idx_name}")
            narrative = narrative_explanation(shap_vals, idx, float(y_pred_sample[idx]))
            logger.info("Narrative [%s %s]: %s", model_key, idx_name, narrative)

        shap_store[model_key] = {"shap_values": shap_vals, "importance": importance}

    # Consistency check RF vs XGBoost
    if "rf" in shap_store and "xgboost" in shap_store:
        corr = consistency_check(shap_store["rf"]["shap_values"], shap_store["xgboost"]["shap_values"])
        results["rf_xgb_shap_correlation"] = corr

    results["shap_store"] = shap_store
    return results


def run_gis_stage(zone_df=None) -> dict:
    """Stage 5: GIS hotspot analysis and maps."""
    import pandas as pd
    from evplan.gis.hotspots import run_hotspot_analysis
    from evplan.gis.coverage import build_map, save_map

    logger.info("=" * 60)
    logger.info("STAGE 5: GIS HOTSPOT ANALYSIS")
    logger.info("=" * 60)

    if zone_df is None:
        p = Path(get_path("data_processed")) / "zone_table.parquet"
        if p.exists():
            zone_df = pd.read_parquet(p)
        else:
            logger.error("Zone table not found. Run features stage first.")
            return {}

    enriched, stats = run_hotspot_analysis(zone_df)
    enriched.to_parquet(str(Path(get_path("data_processed")) / "zones_hotspot.parquet"), index=False)
    logger.info("GIS stats: %s", stats)

    # Build map
    stations_df = None
    sp = Path(get_path("data_processed")) / "stations_clean.parquet"
    if sp.exists():
        stations_df = pd.read_parquet(sp)

    m = build_map(enriched, stations_df=stations_df)
    save_map(m, "hotspot_map.html")

    return {"zone_enriched": enriched, "gis_stats": stats}


def run_recommend_stage(zone_enriched=None) -> dict:
    """Stage 6: Station recommendations."""
    import pandas as pd
    from evplan.recommend.ranking import build_recommendations, validate_recommendations

    logger.info("=" * 60)
    logger.info("STAGE 6: RECOMMENDATIONS")
    logger.info("=" * 60)

    if zone_enriched is None:
        p = Path(get_path("data_processed")) / "zones_hotspot.parquet"
        if p.exists():
            zone_enriched = pd.read_parquet(p)
        else:
            logger.error("Hotspot zone data not found. Run GIS stage first.")
            return {}

    # Load SHAP importance if available
    shap_imp = None
    sp = Path(get_path("tables")) / "shap_importance_xgboost.csv"
    if not sp.exists():
        sp = Path(get_path("tables")) / "shap_importance_rf.csv"
    if sp.exists():
        shap_imp = pd.read_csv(sp)

    cfg = load_config()
    w = cfg["recommendation"]["weights"]
    top_n = cfg["recommendation"]["top_n"]

    recs = build_recommendations(zone_enriched, shap_importance=shap_imp, weights=w, top_n=top_n)
    validation = validate_recommendations(zone_enriched, w, top_n=top_n)

    val_path = get_path("tables") / "recommendation_validation.json"
    val_path.write_text(json.dumps(validation, indent=2, default=str))
    logger.info("Recommendations complete. Top zone: %s", recs.iloc[0].get("zone_id", "?") if len(recs) > 0 else "None")

    # Build map with recommendations
    from evplan.gis.coverage import build_map, save_map
    stations_df = None
    sp2 = Path(get_path("data_processed")) / "stations_clean.parquet"
    if sp2.exists():
        stations_df = pd.read_parquet(sp2)

    m = build_map(zone_enriched, stations_df=stations_df, recommendations_df=recs)
    save_map(m, "recommendation_map.html")

    return {"recommendations": recs, "validation": validation}


def run_all() -> None:
    """Run the complete pipeline end-to-end."""
    cfg = load_config()
    set_global_seed(cfg["project"]["seed"])

    logger.info("[START] EV XAI Planner -- Full Pipeline Start")

    data_results = run_data_stage()
    feat_results = run_features_stage(
        demand_df=data_results.get("demand"),
        stations_df=data_results.get("stations"),
        adoption_df=data_results.get("adoption"),
    )

    if feat_results.get("features") is not None:
        train_results = run_train_stage(feat_results["features"])
        explain_results = run_explain_stage(train_results)
    else:
        train_results = {}
        explain_results = {}

    gis_results = run_gis_stage(feat_results.get("zone_df"))
    rec_results = run_recommend_stage(gis_results.get("zone_enriched"))

    logger.info("[COMPLETE] Pipeline complete! Launch dashboard with: streamlit run app/streamlit_app.py")


def main() -> None:
    parser = argparse.ArgumentParser(description="EV XAI Planner pipeline")
    parser.add_argument(
        "--stage",
        choices=["all", "data", "features", "train", "explain", "gis", "recommend"],
        default="all",
    )
    args = parser.parse_args()

    stage_map = {
        "data": run_data_stage,
        "features": run_features_stage,
        "train": run_train_stage,
        "explain": run_explain_stage,
        "gis": run_gis_stage,
        "recommend": run_recommend_stage,
        "all": run_all,
    }

    stage_map[args.stage]()


if __name__ == "__main__":
    main()
